import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createCatalogIndex } from "@/domain/catalog";
import { seedCatalog } from "./catalog";
import { seedRecipes, tags } from "./recipes";

/**
 * Generates supabase/seed.sql from the TypeScript seed data, so the database and the
 * sample-week script can never disagree about the catalog.
 *
 *   npm run seed:build
 */

const NAMESPACE = "6f1d3c5e8a2b4c7d9e0f1a2b3c4d5e6f";

/** A stable UUID (version 5) for a seed row, so re-generating does not reshuffle ids. */
export function seedId(kind: string, slug: string): string {
  const hash = createHash("sha1")
    .update(Buffer.from(NAMESPACE, "hex"))
    .update(`${kind}:${slug}`)
    .digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.subarray(0, 16).toString("hex");
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20),
  ].join("-");
}

export const SEED_HOUSEHOLD_ID = seedId("household", "default");

type Value = string | number | boolean | null | string[] | Record<string, unknown>;

function literal(value: Value): string {
  if (value === null) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    return value.length === 0 ? "'{}'::text[]" : `array[${value.map(literal).join(", ")}]::text[]`;
  }
  if (typeof value === "object") return `${literal(JSON.stringify(value))}::jsonb`;
  return `'${value.replace(/'/g, "''")}'`;
}

function insert(table: string, columns: string[], rows: Value[][]): string {
  if (rows.length === 0) return "";
  const values = rows.map((row) => `  (${row.map(literal).join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n`;
}

export function buildSeedSql(): string {
  const index = createCatalogIndex(seedCatalog);
  const household = SEED_HOUSEHOLD_ID;
  const shopId = (id: string) => seedId("shop", id);
  const aisleId = (id: string) => seedId("aisle_group", id);
  const ingredientId = (id: string) => seedId("ingredient", id);
  const recipeId = (id: string) => seedId("recipe", id);
  const tagId = (id: string) => seedId("tag", id);

  for (const ingredient of seedCatalog.ingredients) {
    if (!index.shopById.has(ingredient.preferredShopId)) {
      throw new Error(`${ingredient.id}: unknown shop ${ingredient.preferredShopId}`);
    }
    if (!index.aisleGroupById.has(ingredient.aisleGroupId)) {
      throw new Error(`${ingredient.id}: unknown aisle group ${ingredient.aisleGroupId}`);
    }
  }

  const sections = [
    "-- Generated by `npm run seed:build` from supabase/seed/*.ts. Do not edit by hand.\n",
    insert(
      "household",
      ["id", "name", "default_servings", "shopping_weekday"],
      [[household, "Zuhause", 4, 1]],
    ),
    insert(
      "shop",
      ["id", "household_id", "name", "short_label", "sort_order", "is_default"],
      seedCatalog.shops.map((s) => [
        shopId(s.id),
        household,
        s.name,
        s.shortLabel,
        s.sortOrder,
        s.id === seedCatalog.defaultShopId,
      ]),
    ),
    insert(
      "aisle_group",
      ["id", "household_id", "name", "sort_order", "is_fallback"],
      seedCatalog.aisleGroups.map((a) => [
        aisleId(a.id),
        household,
        a.name,
        a.sortOrder,
        a.id === seedCatalog.fallbackAisleGroupId,
      ]),
    ),
    insert(
      "shop_aisle_order",
      ["household_id", "shop_id", "aisle_group_id", "sort_order"],
      seedCatalog.shops.flatMap((s) =>
        Object.entries(s.aisleSortOverrides).map(([aisle, order]): Value[] => [
          household,
          shopId(s.id),
          aisleId(aisle),
          order,
        ]),
      ),
    ),
    insert(
      "ingredient",
      [
        "id",
        "household_id",
        "name",
        "synonyms",
        "aisle_group_id",
        "preferred_shop_id",
        "default_unit",
        "buying_mode",
        "pack_size",
        "rounding_step",
        "grams_per",
        "is_pantry_staple",
        "shelf_life_days",
      ],
      seedCatalog.ingredients.map((i) => [
        ingredientId(i.id),
        household,
        i.name,
        i.synonyms,
        aisleId(i.aisleGroupId),
        shopId(i.preferredShopId),
        i.defaultUnit,
        i.buyingMode,
        i.packSize,
        i.roundingStep,
        i.gramsPer,
        i.isPantryStaple,
        i.shelfLifeDays,
      ]),
    ),
    insert(
      "tag",
      ["id", "household_id", "name", "group_name", "key", "sort_order"],
      tags.map((t, position) => [
        tagId(t.id),
        household,
        t.name,
        t.group,
        t.id,
        (position + 1) * 10,
      ]),
    ),
    insert(
      "recipe",
      [
        "id",
        "household_id",
        "title",
        "source_title",
        "kind",
        "source_book",
        "source_page",
        "servings_min",
        "servings_max",
        "servings_unit",
        "prep_minutes",
        "protein_type",
        "status",
      ],
      seedRecipes.map((r) => [
        recipeId(r.id),
        household,
        r.title,
        r.sourceTitle,
        r.kind,
        r.sourceBook,
        r.sourcePage,
        r.servings.min,
        r.servings.max,
        r.servings.unit,
        r.prepMinutes,
        r.proteinType,
        r.status,
      ]),
    ),
    insert(
      "recipe_tag",
      ["household_id", "recipe_id", "tag_id"],
      seedRecipes.flatMap((r) =>
        r.tagIds.map((tag): Value[] => {
          if (!tags.some((t) => t.id === tag)) throw new Error(`${r.id}: unknown tag ${tag}`);
          return [household, recipeId(r.id), tagId(tag)];
        }),
      ),
    ),
    insert(
      "recipe_ingredient",
      [
        "id",
        "household_id",
        "recipe_id",
        "position",
        "ingredient_id",
        "quantity",
        "quantity_max",
        "unit",
        "is_approximate",
        "is_optional",
        "secondary_quantity",
        "secondary_unit",
        "secondary_scope",
        "alternative_to",
        "original_text",
        "note",
      ],
      seedRecipes.flatMap((r) =>
        r.ingredients.map((line, position): Value[] => {
          if (line.ingredientId === null || !index.ingredientById.has(line.ingredientId)) {
            throw new Error(`${r.id}: "${line.originalText}" is not mapped to the catalog`);
          }
          if (line.alternativeTo !== null && line.alternativeTo >= position) {
            throw new Error(`${r.id}: an alternative must follow the line it replaces`);
          }
          const lineId = (at: number) => seedId("recipe_ingredient", `${r.id}:${at}`);
          return [
            lineId(position),
            household,
            recipeId(r.id),
            position,
            ingredientId(line.ingredientId),
            line.quantity,
            line.quantityMax,
            line.unit,
            line.approximate,
            line.optional,
            line.secondary?.quantity ?? null,
            line.secondary?.unit ?? null,
            line.secondary?.scope ?? null,
            line.alternativeTo === null ? null : lineId(line.alternativeTo),
            line.originalText,
            line.note,
          ];
        }),
      ),
    ),
  ];
  return sections.filter(Boolean).join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL("../seed.sql", import.meta.url));
  writeFileSync(target, buildSeedSql());
  console.log(`wrote ${target}`);
}
